# 读取现有 labels
existing_labels = set()
rows = []
with open(CSV, "r", encoding="utf-8") as f:
    reader = csv.DictReader(f)
    fieldnames = reader.fieldnames
    for row in reader:
        rows.append(row)
        existing_labels.add(row["label"].strip())

# 追加新类别
added = 0
with open(CSV, "a", encoding="utf-8", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=fieldnames)
    for label, texts in SAMPLES.items():
        if label in existing_labels:
            print(f"  跳过（已存在）: {label}")
            continue
        for t in texts:
            writer.writerow({"text": t, "label": label})
            added += 1
        print(f"  已追加: {label} ({len(texts)} 条)")

print(f"\n✅ 共追加 {added} 条样本 → {CSV}")
